// 세기 상태 n 겹이 하는 일 — 사기 3 → 0.6. 최대 겹 · 불굴Cap 을 지킨다
export function stackEff(id, n) {
  const k = Math.max(0, Math.min(n || 0, STATUS_V[id + "Max"] ?? Infinity));
  const v = k * (STATUS_V[id] || 0);
  return id === "불굴" ? Math.min(v, STATUS_V.불굴Cap) : v;
}
