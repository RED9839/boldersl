// 회복력 — 회복은 공격력이 아니라 회복력으로 센다(카드 글 「HP 회복(회복력 N%)」).
// 회복력 = 공격력 + 역할 몫. 공격력이 낮은 서포터 · 탱커도 치료가 바닥까지 꺼지지 않게 받쳐 주는 몫이고,
// 딜러는 몫이 없어 전과 같다. 공격력 장비 · 버프는 그대로 회복력에도 붙는다.
// (전에는 공격력에 역할 배율 서포터 ×1.8 · 탱커 ×1.3 을 곱했다 — 공격력 6 서포터는 10.8, 공격력 7 탱커는 9.1 에 그쳤다)
export const HEAL_BONUS = { 서포터: 12, 탱커: 7, 딜러: 0 };
// extra — 장비 스탯 줄의 「회복력 +N」(공격력과 따로 붙는 몫 · run.js gearStats → combat u.healPlus)
export const healStat = (atk, role, extra = 0) => atk + (HEAL_BONUS[role] || 0) + (extra || 0);
export const NATURE_DEF = 0.05;
// 약점 성격 — 그 성격을 이기는 성격들(광기 적 → 냉정, 활발 적 → 우울). 적마다 enemies.js 의 weak 로 바꿀 수 있다(combat.js weakOf)
export const weakTo = (nature) => Object.keys(BEATS).filter((k) => BEATS[k] === nature);
export function natureEdge(attacker, defender) {
  if (!attacker || !defender) return 0;
  if (BEATS[attacker] === defender) return 1;    // 내가 유리
  if (BEATS[defender] === attacker) return -1;   // 상대가 유리
  return 0;
}

// ── 전역 증가·감소 ────────────────────────────────────────────────────
// 같은 종류는 가장 큰 값 하나만, 다른 종류끼리는 더한다.
export const GLOBAL_KINDS = [
  "주는피해", "기본공격피해", "고유카드피해", "고학년 스킬피해", "위치별피해", "받는피해감소", "상성", "취약약화",
];
export function globalBonus(mods) {
  // mods: [{kind, v}] — v 는 0.07 처럼 비율
  const best = {};
  for (const m of mods || []) best[m.kind] = Math.max(best[m.kind] || 0, m.v);
  return Object.values(best).reduce((a, b) => a + b, 0);
}

// ── 최종 피해 ─────────────────────────────────────────────────────────
// 기획서의 계산식 그대로:
//   최종 = 스탯 × (카드 배율 + 신탁) × 기적(×1.3) × (1 + 전역 증가) × 치명(×1.5)
// 소수점은 반올림하고, 증가가 있으면 최소 +1.
export const SHIN = 1.3;
export function finalDamage({ stat, ratio, flash = 0, shin = false, global = 0, crit = false }) {
  let v = stat * (ratio + flash);
  if (shin) v *= SHIN;
  v *= 1 + global;
  if (crit) v *= CRIT_MULT;
  const out = Math.round(v);
  // "증가가 있으면 최소 +1" — 보정이 붙었는데 0 이 되면 안 된다
  if (out === 0 && stat * ratio > 0) return 1;
  return out;
}

// 배율은 기획서에 % 로 적혀 있다(공격력 100%) — 0~1 이 아니라 1.0 이다
export const pct = (n) => n / 100;

// ── 강화 카드 — 사도마다 한 장(docs/15 §7) ──────────────────────────────
// 그 사도의 고유 카드 가운데 종류가 「강화」 인 것. 카제나의 강화 카드처럼:
//   한 장만   덱에 한 장까지 — 은총 · 이벤트 · 상점이 이미 가진(또는 써 버린) 것을 다시 내놓지 않고, 복제도 안 된다
//   쓰면 사라짐  내면 이 전투에서 사라지고(소멸), 판의 덱(run.deck)에서도 빠진다. 이 판에서는 다시 안 나온다(run.spent)
//   판 내내   글의 「판 내내 자신 공격력 +10%」 는 그 자리에서 걸리고, 판이 끝날 때까지 다음 전투마다 다시 걸린다(run.boons)
// 교주 카드의 「강화」(사기진작 따위)는 사도 카드가 아니라 이 규칙 밖이다 — 그쪽은 「덱에 1장만.」(oneOnly)이 따로 있다
// 고유 카드의 신탁 하나가 「강화 카드.」 로 시작하면 그 신탁을 고른 카드도 강화 카드다 — c 에 신탁을 얹은 카드(cardbook flashed)를 넘긴다
export const isPower = (c) => !!(c && c.unique && c.hero && c.type === "강화");
// 유일(카제나 「유일을 가진 같은 카드는 1장만 보유할 수 있음」) — 덱에 한 장까지. 한 개념 · 한 길:
//   카드 키워드 「유일.」 · 교주 카드 「덱에 1장만.」(옛 글, oneOnly) · 사도의 강화 카드(isPower) 모두 이것으로 본다.
//   은총 · 이벤트 · 상점 · 보상이 이미 가진 것을 다시 내놓지 않고(run.js powerWhy · neutral 진열), 복제 · 보스 복제도 안 된다(events.js dupeOk · run.js bossCopy)
//   c 는 신탁을 얹은 카드(cardbook flashed)를 넘긴다 — 「강화 카드.」 신탁을 고른 카드도 유일이다
export const isOnly = (c) => !!c && (!!c.oneOnly || isPower(c) || (c.tags || []).includes("유일") || (c.fx || []).some((f) => f.k === "tag" && f.id === "유일"));
// 판 내내 증감이 남는 턴 — 전투 하나보다 길게(999 는 「이번 전투 동안」). 화면은 이 값 이상이면 「판 내내」 라고 적는다
export const BOON_TURNS = 9999;
