export const STAT_ST = { atk: "열의", def: "강건", crit: "집중", heal: "온정" };
// 횟수로 도는 상태 — 한 번 돌 때마다 1 준다(combat.js charge)
export const CHARGE_ST = ["취약", "약화", "손상", "반격", "표식"];
// 세기로 도는 상태 — 겹마다 효과, 줄지 않는다(전투 내내)
