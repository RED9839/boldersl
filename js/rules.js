//
// 겹(중첩) 규칙 — 카제나 용어집(kazena.co.kr/glossary/type/effect) 그대로(2026-10 사용자). 상태는 두 갈래다:
//   횟수(CHARGE_ST) — 「발동하면 1 감소」. 효과는 정해져 있고, 한 번 돌 때마다 1 줄어든다. 턴이 지나도 안 준다.
//     한 번 = 한 번의 일 — 카드 한 장 · 적의 수 하나(여러 번 쳐도 한 번). 다시 걸면 겹이 더해진다.
//     취약 · 약화  맞는 쪽 · 때리는 쪽 — 맞는 일 · 피해를 주는 카드(적은 공격하는 수) 하나에 1 씩
//     손상         방어 · 실드를 얻는 일 하나에 1 씩(얻는 양 -손상%)
//     반격         적의 수에 맞으면 그 적에게 방어력 반격% 피해, 1 줄어든다
//     표식         그 적을 공격 카드로 치면 공격력 표식% 덤 타격 + 강인도 1, 1 줄어든다
//   세기(INTENSITY_ST) — 「사기마다 피해량 +20%」. 겹마다 효과가 곱이 아니라 더해 커지고(사기 3 = +60%), **줄지 않는다** — 전투 내내.
//     카드 · 턴 · 맞는 일 어느 것도 겹을 쓰지 않는다. 겹은 …Max 까지만 쌓인다(사도 10 · 적 FOE_INT_MAX).
//     사기 주는 피해 +  · 불굴 받는 피해 -(합쳐서 불굴Cap 까지 — 그 넘는 겹은 하는 일이 없다) · 결의 얻는 방어 · 실드 +(겹마다 결의, 고정 수)
//     결정화 턴 끝에 겹마다 방어력 결정화% 실드 · 열의 공격력 + · 강건 방어력 + · 집중 치명 확률 +(%p) · 온정 회복력 +
//   고통 — (겹이 곧 세기) 턴 끝에 겹 × 고통 만큼 고정 피해(방어 · 실드를 무시), 그 뒤 겹이 절반(내림). 최대 고통Max
// 결의는 카제나 「결의 중첩마다 실드 획득량 +20」 의 꼴 그대로(고정 수)지만 눈금은 우리 것이다 — 카제나 실드 한 장이 100 언저리라면
// 우리는 방어력 3 × 150% ≈ 5 다. 그래서 +20 이 아니라 +1(카드 한 장 실드의 2할 언저리)
// 키워드 수치 — 분쇄(방어 · 실드가 있는 적) · 잔불(격파된 적) · 잔광(격파된 적. 강인도 +1 은 TOUGH.glow)
// 격파 자체에는 받는 피해 증가가 없다(카제나에 없다, 2026-10 사용자) — 덤 피해는 잔불 · 잔광 · 파괴에서만 온다
export const STATUS_V = {
  취약: 0.5, 약화: 0.25, 손상: 0.5, 반격: 1.5, 표식: 1.0,
  사기: 0.2, 불굴: 0.2, 불굴Cap: 0.8, 결의: 1, 결정화: 0.2,
  열의: 0.2, 강건: 0.2, 집중: 0.2, 온정: 0.2,
  사기Max: 10, 불굴Max: 10, 결의Max: 10, 결정화Max: 10, 열의Max: 10, 강건Max: 10, 집중Max: 10, 온정Max: 10,
  고통: 1, 고통Max: 20,
  분쇄: 0.2, 잔불: 0.4, 잔광: 0.5,
};
// 적이 얻는 세기 상태의 최대 — 적은 턴마다 사기 · 불굴을 쌓는 수가 있어 전투가 길면 끝없이 커진다. 적 하나에 이 겹까지
