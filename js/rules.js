// ── 상태(카제나, docs/16-카제나전투.md) ─────────────────────────────────
// 수치는 전부 아래 STATUS_V 한 표에 있다. 엔진(combat.js) · 봇(tools/lib/bot.js) · 풀이(build-keywords) · 도움말이 여기서 읽는다.
