export function natureEdge(attacker, defender) {
  if (!attacker || !defender) return 0;
  if (BEATS[attacker] === defender) return 1;    // 내가 유리
  if (BEATS[defender] === attacker) return -1;   // 상대가 유리
  return 0;
}

// ── 전역 증가·감소 ────────────────────────────────────────────────────
// 같은 종류는 가장 큰 값 하나만, 다른 종류끼리는 더한다.
export const GLOBAL_KINDS = [
  "주는피해", "기본공격피해", "고유카드피해", "고학년 스킬피해", "위치별피해", "받는피해감소", "상성", "취약약화",
];
export function globalBonus(mods) {
  // mods: [{kind, v}] — v 는 0.07 처럼 비율
  const best = {};
  for (const m of mods || []) best[m.kind] = Math.max(best[m.kind] || 0, m.v);
  return Object.values(best).reduce((a, b) => a + b, 0);
}

// ── 최종 피해 ─────────────────────────────────────────────────────────
// 기획서의 계산식 그대로:
//   최종 = 스탯 × (카드 배율 + 신탁) × 기적(×1.3) × (1 + 전역 증가) × 치명(×1.5)
// 소수점은 반올림하고, 증가가 있으면 최소 +1.
export const SHIN = 1.3;
export function finalDamage({ stat, ratio, flash = 0, shin = false, global = 0, crit = false }) {
  let v = stat * (ratio + flash);
  if (shin) v *= SHIN;
  v *= 1 + global;
  if (crit) v *= CRIT_MULT;
  const out = Math.round(v);
  // "증가가 있으면 최소 +1" — 보정이 붙었는데 0 이 되면 안 된다
  if (out === 0 && stat * ratio > 0) return 1;
  return out;
}

